#!/usr/bin/env bash
# ============================================================================
# utils.sh - Вспомогательные утилиты
# ============================================================================

# ============================================================================
# Проверка наличия файла
# ============================================================================

file_exists() {
    [[ -f "$1" ]]
    return $?
}

# ============================================================================
# Проверка наличия директории
# ============================================================================

dir_exists() {
    [[ -d "$1" ]]
    return $?
}

# ============================================================================
# Получение размера файла
# ============================================================================

get_file_size() {
    local file="$1"
    if [[ -f "$file" ]]; then
        du -h "$file" 2>/dev/null | cut -f1
    else
        echo "N/A"
    fi
}

# ============================================================================
# Получение даты файла
# ============================================================================

get_file_date() {
    local file="$1"
    if [[ -f "$file" ]]; then
        stat -c '%y' "$file" 2>/dev/null | cut -d' ' -f1 || echo "Unknown"
    else
        echo "Unknown"
    fi
}

# ============================================================================
# Подтверждение действия
# ============================================================================

confirm_action() {
    local message="${1:-Вы уверены?}"
    echo -n "$message [y/N]: "
    read -r response
    [[ "$response" =~ ^[Yy]$ ]]
    return $?
}

# ============================================================================
# Проверка целочисленного значения
# ============================================================================

is_integer() {
    [[ "$1" =~ ^-?[0-9]+$ ]]
    return $?
}

# ============================================================================
# Проверка значения в диапазоне
# ============================================================================

is_in_range() {
    local value="$1"
    local min="$2"
    local max="$3"
    
    if is_integer "$value" && is_integer "$min" && is_integer "$max"; then
        [[ "$value" -ge "$min" ]] && [[ "$value" -le "$max" ]]
        return $?
    fi
    return 1
}

# ============================================================================
# Форматирование вывода
# ============================================================================

print_header() {
    echo -e "\n${CLR_TITLE}═══════════════════════════════════════════════════════${C_RESET}"
    echo -e "${CLR_TITLE}  $1${C_RESET}"
    echo -e "${CLR_TITLE}═══════════════════════════════════════════════════════${C_RESET}"
}

print_separator() {
    echo -e "${CLR_INFO}----------------------------------------${C_RESET}"
}