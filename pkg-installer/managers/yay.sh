#!/usr/bin/env bash
#
# managers/yay.sh
#

################################################################################
# Проверка существования пакета
################################################################################

pkg_exists_yay() {

    local package="$1"

    yay -Si "$package" &>/dev/null
}

################################################################################
# Установка пакетов
################################################################################

install_yay() {

    (($# == 0)) && return 0

    yay \
        -S \
        --needed \
        --noconfirm \
        "$@"
}