#!/usr/bin/env bash
#
# path_helpers.sh
#
# Вспомогательные функции для построения путей.
#
# Требует:
#   ROOT_DIR и CONFIGS_DIR из lib/init.sh и lib/core.sh
#

[[ -n "${__PATH_HELPERS_SH:-}" ]] && return
readonly __PATH_HELPERS_SH=1

# ---------------------------------------------------------------------
# project_path
# ---------------------------------------------------------------------

##
# Возвращает путь внутри корня проекта.
#
# Usage:
#   project_path "<relative/path>"
#

project_path() {
    printf "%s\n" "$ROOT_DIR/$1"
}

# ---------------------------------------------------------------------
# config_path
# ---------------------------------------------------------------------

##
# Возвращает путь внутри каталога конфигураций.
#
# Usage:
#   config_path "<name>"
#

config_path() {
    printf "%s\n" "$CONFIGS_DIR/$1"
}

# ---------------------------------------------------------------------
# lib_path
# ---------------------------------------------------------------------

##
# Возвращает путь внутри каталога библиотек.
#
# Usage:
#   lib_path "<name>"
#

lib_path() {
    printf "%s\n" "$LIB_DIR/$1"
}