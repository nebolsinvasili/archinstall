#!/usr/bin/env bash
#
# env.sh
#
# Переменные окружения: PATH и локаль.
#
# Требует:
#   ROOT_DIR из lib/init.sh
#

[[ -n "${__ENV_SH:-}" ]] && return
readonly __ENV_SH=1

# ---------------------------------------------------------------------
# PATH
# ---------------------------------------------------------------------

# Каталог для собственных исполняемых файлов проекта.
mkdir -p "$ROOT_DIR/bin"

export PATH="$ROOT_DIR/bin:$PATH"

# ---------------------------------------------------------------------
# Локаль
# ---------------------------------------------------------------------

export LC_ALL=C.UTF-8
export LANG=C.UTF-8