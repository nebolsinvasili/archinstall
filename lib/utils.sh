#!/usr/bin/env bash
#
# utils.sh
#
# Общие вспомогательные функции.
#

[[ -n "${__UTILS_SH:-}" ]] && return
readonly __UTILS_SH=1

################################################################################
# command_exists
################################################################################

##
# Проверяет наличие команды в PATH.
#
# Usage:
#
#   if command_exists jq; then
#       echo "jq exists"
#   fi
#
command_exists() {

    command -v "$1" >/dev/null 2>&1

}


################################################################################
# require_command
################################################################################

##
# Проверяет наличие обязательной команды.
#
# Parameters:
#   $1 command name
#
require_command() {

    local command="$1"

    if ! command_exists "$command"; then

        log_error \
            "Required command not found: ${command}"

        return 1

    fi

}


################################################################################
# array_empty
################################################################################

##
# Проверяет пустой ли массив.
#
# Parameters:
#   $1 - имя массива
#
# Return:
#   0 - массив пуст
#   1 - содержит элементы
#
array_empty() {

    local array_name="$1"

    declare -n array="$array_name"

    (( ${#array[@]} == 0 ))

}


################################################################################
# join_by
################################################################################

##
# Объединяет элементы массива через разделитель.
#
# Usage:
#
#   join_by "," a b c
#
# Result:
#
#   a,b,c
#
join_by() {

    local separator="$1"

    shift

    local first=true
    local item

    for item in "$@"; do

        if [[ "$first" == true ]]; then

            first=false

        else

            printf '%s' "$separator"

        fi

        printf '%s' "$item"

    done

}


################################################################################
# trim
################################################################################

##
# Удаляет пробелы в начале и конце строки.
#
# Usage:
#
#   trim "  hello "
#
# Output:
#
#   hello
#
trim() {

    local value="$*"

    value="${value#"${value%%[![:space:]]*}"}"

    value="${value%"${value##*[![:space:]]}"}"

    printf '%s' "$value"

}


################################################################################
# file_exists
################################################################################

##
# Проверяет существование файла.
#
file_exists() {

    [[ -f "$1" ]]

}


################################################################################
# directory_exists
################################################################################

##
# Проверяет существование каталога.
#
directory_exists() {

    [[ -d "$1" ]]

}
