-- ==========================================================================
-- 1. KANAGAWA THEME
-- ==========================================================================

-- Import user environment settings
local env = require("config.user_env").config

return {
	"rebelot/kanagawa.nvim",
	lazy = false, -- Load immediately during startup
	priority = 1000, -- Load before other UI plugins

	config = function()
		-- ----------------------------------------------------------------------
		-- 1. UI Setup: Diagnostic Signs
		-- ----------------------------------------------------------------------
		-- Define custom icons for LSP diagnostics in the sign column.
		local signs = {
			Error = "",
			Warn = "",
			Hint = "",
			Info = "",
		}

		for type, icon in pairs(signs) do
			local hl = "DiagnosticSign" .. type
			vim.fn.sign_define(hl, { text = icon, texthl = hl, numhl = "" })
		end

		-- ----------------------------------------------------------------------
		-- 2. Theme Configuration
		-- ----------------------------------------------------------------------
		require("kanagawa").setup({
			compile = true, -- Enable compiling the colorscheme
			undercurl = true, -- Enable undercurls
			float = {
				transparent = true, -- enable transparent floating windows
				solid = false, -- use solid styling for floating windows, see |winborder|
			},
			show_end_of_buffer = false, -- shows the '~' characters after the end of buffers
			term_colors = false, -- sets terminal colors (e.g. `g:terminal_color_0`)
			dim_inactive = {
				enabled = false, -- dims the background color of inactive window
				shade = "dark",
				percentage = 0.15, -- percentage of the shade to apply to the inactive window
			},
			no_italic = false, -- Force no italic
			no_bold = false, -- Force no bold
			no_underline = false, -- Force no underline
			styles = { -- Handles the styles of general hi groups (see `:h highlight-args`):
				comments = { "italic" }, -- Change the style of comments
				conditionals = { "italic" },
				loops = {},
				functions = {},
				keywords = {},
				strings = {},
				variables = {},
				numbers = {},
				booleans = {},
				properties = {},
				types = {},
				operators = {},
				-- miscs = {}, -- Uncomment to turn off hard-coded styles
			},
			lsp_styles = { -- Handles the style of specific lsp hl groups (see `:h lsp-highlight`).
				virtual_text = {
					errors = { "italic" },
					hints = { "italic" },
					warnings = { "italic" },
					information = { "italic" },
					ok = { "italic" },
				},
				underlines = {
					errors = { "underline" },
					hints = { "underline" },
					warnings = { "underline" },
					information = { "underline" },
					ok = { "underline" },
				},
				inlay_hints = {
					background = true,
				},
			},
			color_overrides = {},
			custom_highlights = {},
			default_integrations = true,
			auto_integrations = false,
			integrations = {
				cmp = true,
				gitsigns = true,
				nvimtree = true,
				notify = false,
				mini = {
					enabled = true,
					indentscope_color = "",
				},
				-- For more plugins integrations please scroll down (https://github.com/catppuccin/nvim#integrations)
			},
		})

		-- ----------------------------------------------------------------------
		-- 3. Load Colorscheme
		-- ----------------------------------------------------------------------
		-- Applies the theme defined in user_env (defaults to "kanagawa")
		vim.cmd.colorscheme(env.theme)
	end,
}
